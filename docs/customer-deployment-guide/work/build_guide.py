def table(headers,rows,widths=None):
    t=doc.add_table(rows=1, cols=len(headers));t.alignment=WD_TABLE_ALIGNMENT.CENTER;t.autofit=False
    if widths:
        for c,w in zip(t.columns,widths):c.width=Cm(w)
    for i,txt in enumerate(headers):t.rows[0].cells[i].text=txt
    for row in rows:
        cells=t.add_row().cells
        for i,txt in enumerate(row):cells[i].text=str(txt)
    for ri,row in enumerate(t.rows):
        for ci,c in enumerate(row.cells):
            if widths:c.width=Cm(widths[ci])
            c.vertical_alignment=WD_CELL_VERTICAL_ALIGNMENT.CENTER
            pr=c._tc.get_or_add_tcPr()
            borders=OxmlElement('w:tcBorders')
            for tag in ['top','left','bottom','right']:
                x=OxmlElement('w:'+tag);x.set(qn('w:val'),'single');x.set(qn('w:sz'),'4');x.set(qn('w:color'),'D9D9D9');borders.append(x)
            pr.append(borders)
            margins=OxmlElement('w:tcMar')
            for tag in ['top','left','bottom','right']:
                x=OxmlElement('w:'+tag);x.set(qn('w:w'),'85');x.set(qn('w:type'),'dxa');margins.append(x)
            pr.append(margins)
            shade=OxmlElement('w:shd');shade.set(qn('w:fill'),'DDE9F4' if ri==0 else ('F5F7F9' if ri%2==0 else 'FFFFFF'));pr.append(shade)
            for para in c.paragraphs:
                para.paragraph_format.space_after=Pt(2);para.paragraph_format.line_spacing=1.1
                for run in para.runs:run.font.size=Pt(9);run.bold=(ri==0)
        if ri==0:
            repeat=OxmlElement('w:tblHeader');row._tr.get_or_add_trPr().append(repeat)
        else:
            nosplit=OxmlElement('w:cantSplit');row._tr.get_or_add_trPr().append(nosplit)
    p('') .paragraph_format.space_after=Pt(0)
    return t

